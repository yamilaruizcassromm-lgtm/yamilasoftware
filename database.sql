-- 1. Crear la tabla para almacenar el cuestionario o apuntes
CREATE TABLE IF NOT EXISTS public.respuestas_tarea (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pregunta_numero INT NOT NULL,
    pregunta_texto TEXT NOT NULL,
    respuesta_texto TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Habilitar la seguridad a nivel de filas (RLS)
ALTER TABLE public.respuestas_tarea ENABLE ROW LEVEL SECURITY;

-- 3. Crear política para permitir la lectura pública de las respuestas
CREATE POLICY "Permitir lectura publica" 
ON public.respuestas_tarea 
FOR SELECT 
USING (true);

